def scaffold_and_lock(cells) -> None:
    lock = {"schema": "wellmanifest.polycell.lock/v1", "cells": {}}
    for c in cells:
        if not c.cell_path.exists():
            write(c.cell_path, STUB[c.owner].format(urn=c.urn, h=c.interface_hash, P=c.pascal, name=c.name))
        hdr = read_header(c.cell_path) or {}
        lock["cells"][c.urn] = {
            "contract": c.interface_hash, "owner": c.owner,
            "cell": str(c.cell_path.relative_to(ROOT)), "cell_sha": file_sha(c.cell_path),
            "header_contract": hdr.get("hash"),
            "status": "ok" if hdr.get("hash") == c.interface_hash else "stale",
        }
    write(ROOT / "contracts" / "polycell.lock.json", jdump(lock))


def main() -> None:
    cells = load_cells()
    processes = load_processes()
    types = all_types(cells)
    print(f"polycell gen: {len(cells)} cells, {len(processes)} processes")
    gen_jsonschema(cells, types)
    gen_proto(cells, types)
    gen_ts(cells, types)
    gen_python(cells, types)
    gen_rust(cells, types)
    gen_sql(cells)
    gen_registry(cells, processes)
    gen_openapi_mcp(cells)
    gen_tests(cells, processes)
    scaffold_and_lock(cells)


if __name__ == "__main__":
    main()
