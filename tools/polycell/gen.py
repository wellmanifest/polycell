GEN = ROOT / "gen"
BANNER = "GENERATED by tools/polycell/gen.py - DO NOT EDIT (edit contracts/ instead)"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        print(f"  wrote {path.relative_to(ROOT)}")


def jdump(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


# ---------------------------------------------------------------- type mapping
PROTO = {"string": "string", "int32": "int32", "int64": "int64", "double": "double",
         "bool": "bool", "json": "google.protobuf.Struct"}
TS = {"string": "string", "int32": "number", "int64": "number", "double": "number",
      "bool": "boolean", "json": "unknown"}
PY = {"string": "str", "int32": "int", "int64": "int", "double": "float", "bool": "bool", "json": "Any"}
RS = {"string": "String", "int32": "i32", "int64": "i64", "double": "f64", "bool": "bool",
      "json": "serde_json::Value"}
JS = {"string": {"type": "string"}, "int32": {"type": "integer"}, "int64": {"type": "integer"},
      "double": {"type": "number"}, "bool": {"type": "boolean"}, "json": {}}
SQL = {"string": "text", "int32": "integer", "int64": "bigint", "double": "double precision",
       "bool": "boolean", "json": "jsonb"}


def ts_t(t: TypeRef) -> str:
    b = TS.get(t.base, t.base)
    return f"{b}[]" if t.is_list else b


def py_t(t: TypeRef) -> str:
    b = PY.get(t.base, t.base)
    b = f"list[{b}]" if t.is_list else b
    return f"NotRequired[{b} | None]" if t.optional else b


def rs_t(t: TypeRef) -> str:
    b = RS.get(t.base, t.base)
    b = f"Vec<{b}>" if t.is_list else b
    return f"Option<{b}>" if t.optional else b


def js_t(t: TypeRef) -> dict:
    s = dict(JS[t.base]) if t.scalar else {"$ref": f"#/$defs/{t.base}"}
    return {"type": "array", "items": s} if t.is_list else s


def js_obj(fields: dict[str, TypeRef]) -> dict:
    return {"type": "object", "additionalProperties": False,
            "properties": {k: js_t(v) for k, v in fields.items()},
            "required": [k for k, v in fields.items() if not v.optional]}


# ---------------------------------------------------------------- emitters
def gen_jsonschema(cells: list[Cell], types) -> None:
    defs = {t: js_obj(f) for t, f in types.items()}
    for c in cells:
        for kind, fields in (("input", c.input), ("output", c.output)):
            schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
                      "$id": f"{c.urn}#{kind}", "title": f"{c.pascal}{kind.title()}",
                      **js_obj(fields), "$defs": defs}
            write(GEN / "jsonschema" / f"{c.name}.{kind}.json", jdump(schema))


def gen_proto(cells: list[Cell], types) -> None:
    lines = [f"// {BANNER}", 'syntax = "proto3";', "package shop.cells.v1;", "",
             'import "google/protobuf/struct.proto";', ""]

    def msg(name, fields):
        lines.append(f"message {name} {{")
        for i, (k, t) in enumerate(fields.items(), 1):
            pt = PROTO.get(t.base, t.base)
            lab = "repeated " if t.is_list else ("optional " if t.optional else "")
            lines.append(f"  {lab}{pt} {k} = {i};")
        lines.append("}")
        lines.append("")

    for t, f in types.items():
        msg(t, f)
    for c in cells:
        lines.append(f"// {c.urn}  owner={c.owner}  contract={c.interface_hash}")
        msg(f"{c.pascal}Input", c.input)
        msg(f"{c.pascal}Output", c.output)
    lines.append("// Typowany fasadowy serwis (opcjonalny). Uniwersalny transport to polycell.v1.CellHost.")
    lines.append("service ShopCells {")
    for c in cells:
        lines.append(f"  rpc {c.pascal}({c.pascal}Input) returns ({c.pascal}Output);")
    lines.append("}")
    write(GEN / "proto" / "shop" / "cells.proto", "\n".join(lines) + "\n")


def gen_ts(cells, types) -> None:
    out = [f"// {BANNER}", ""]
    for t, f in types.items():
        out.append(f"export interface {t} {{")
        out += [f"  {k}{'?' if v.optional else ''}: {ts_t(v)}{' | null' if v.optional else ''};" for k, v in f.items()]
        out += ["}", ""]
    for c in cells:
        for kind, fields in (("Input", c.input), ("Output", c.output)):
            out.append(f"/** {c.urn} */")
            out.append(f"export interface {c.pascal}{kind} {{")
            out += [f"  {k}{'?' if v.optional else ''}: {ts_t(v)}{' | null' if v.optional else ''};" for k, v in fields.items()]
            out += ["}", ""]
    out.append("export const CELLS = " + json.dumps({c.urn: {"name": c.name, "owner": c.owner,
               "contract": c.interface_hash} for c in cells}, indent=2) + " as const;")
    write(GEN / "ts" / "types.ts", "\n".join(out) + "\n")


def gen_python(cells, types) -> None:
    out = [f"# {BANNER}", "from __future__ import annotations", "",
           "from typing import Any, NotRequired, TypedDict", ""]
    for t, f in types.items():
        out.append(f"class {t}(TypedDict):")
        out += [f"    {k}: {py_t(v)}" for k, v in f.items()] or ["    pass"]
        out += ["", ""]
    for c in cells:
        for kind, fields in (("Input", c.input), ("Output", c.output)):
            out.append(f"class {c.pascal}{kind}(TypedDict):")
            out.append(f'    """{c.urn}"""')
            out += [f"    {k}: {py_t(v)}" for k, v in fields.items()]
            out += ["", ""]
    out.append("CELLS = " + json.dumps({c.urn: {"name": c.name, "owner": c.owner,
               "contract": c.interface_hash} for c in cells}, indent=4))
    write(GEN / "python" / "polycell_types.py", "\n".join(out) + "\n")


def gen_rust(cells, types) -> None:
    out = [f"// {BANNER}", "use serde::{Deserialize, Serialize};", ""]

    def strukt(name, fields, doc=None):
        if doc:
            out.append(f"/// {doc}")
        out.append("#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]")
        out.append("#[serde(deny_unknown_fields)]")
        out.append(f"pub struct {name} {{")
        for k, v in fields.items():
            if v.optional:
                out.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
            out.append(f"    pub {k}: {rs_t(v)},")
        out.extend(["}", ""])

    for t, f in types.items():
        strukt(t, f)
    for c in cells:
        strukt(f"{c.pascal}Input", c.input, c.urn)
        strukt(f"{c.pascal}Output", c.output, c.urn)
    write(GEN / "rust" / "types.rs", "\n".join(out).rstrip() + "\n")

    rs_cells = [c for c in cells if c.owner == "rust"]
    reg = [f"// {BANNER}", "// Rejestr komórek Rust: URN -> funkcja. Kompilowany do hosta przez include!().", ""]
    reg.append("pub mod cells {")
    for c in rs_cells:
        reg.append(f"    pub mod {c.snake} {{ include!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../../cells/rust/{c.snake}.rs\")); }}")
    reg += ["}", "",
            "pub fn dispatch(urn: &str, input: serde_json::Value) -> Result<serde_json::Value, String> {",
            "    match urn {"]
    for c in rs_cells:
        reg.append(f'        "{c.urn}" => {{')
        reg.append(f"            let i: crate::types::{c.pascal}Input = serde_json::from_value(input).map_err(|e| format!(\"input: {{e}}\"))?;")
        reg.append(f"            let o = cells::{c.snake}::run(i)?;")
        reg.append("            serde_json::to_value(o).map_err(|e| e.to_string())")
        reg.append("        }")
    reg += ['        _ => Err(format!("unknown urn: {urn}")),', "    }", "}", "",
            "pub const CELLS: &[(&str, &str, &str)] = &["]
    for c in rs_cells:
        reg.append(f'    ("{c.urn}", "{c.interface_hash}", "cells/rust/{c.snake}.rs"),')
    reg.append("];")
    write(GEN / "rust" / "registry.rs", "\n".join(reg) + "\n")


def gen_sql(cells) -> None:
    pg = [f"-- {BANNER}",
          "-- Uniwersalny dziennik: każde wywołanie dowolnego API/protokołu ląduje tutaj (envelope).",
          "create table if not exists wm_invocations (",
          "  id bigserial primary key,",
          "  trace_id text not null,",
          "  urn text not null,",
          "  transport text not null,",
          "  lang text,",
          "  ok boolean not null,",
          "  input jsonb,",
          "  output jsonb,",
          "  error text,",
          "  duration_ms double precision,",
          "  contract text,",
          "  created_at timestamptz not null default now()",
          ");",
          "create index if not exists wm_invocations_urn on wm_invocations(urn);",
          "create table if not exists wm_process_runs (",
          "  id bigserial primary key,",
          "  trace_id text not null,",
          "  process_ref text not null,",
          "  ok boolean not null,",
          "  input jsonb,",
          "  output jsonb,",
          "  receipt jsonb,",
          "  created_at timestamptz not null default now()",
          ");", ""]
    for c in cells:
        tbl = (c.raw.get("persist") or {}).get("table")
        if not tbl:
            continue
        pg.append(f"-- projekcja {c.urn} (contract={c.interface_hash})")
        pg.append(f"create table if not exists {tbl} (")
        pg.append("  id bigserial primary key,")
        pg.append("  trace_id text not null,")
        for prefix, fields in (("in", c.input), ("out", c.output)):
            for k, v in fields.items():
                col = "jsonb" if (v.is_list or not v.scalar) else SQL[v.base]
                pg.append(f"  {prefix}_{k} {col},")
        pg.append("  created_at timestamptz not null default now()")
        pg.append(");")
        pg.append("")
    text = "\n".join(pg)
    write(GEN / "sql" / "schema.postgres.sql", text)
    lite = (text.replace("bigserial primary key", "integer primary key autoincrement")
            .replace("jsonb", "text").replace("double precision", "real")
            .replace("timestamptz not null default now()", "text not null default current_timestamp"))
    write(GEN / "sql" / "schema.sqlite.sql", lite)


def REG_T(t: TypeRef) -> str:  # typy parametrów wg wellmanifest.api-registry/v1 (nl-api-llm)
    if t.is_list:
        return "array"
    return {"string": "string", "int32": "integer", "int64": "integer", "double": "number",
            "bool": "boolean"}.get(t.base, "object")


def gen_registry(cells, processes) -> None:
    services = [
        {"id": "gateway", "name": "Polycell Gateway (REST/NL/MCP/proces POA)", "protocol": "rest",
         "baseUrl": "http://127.0.0.1:8080", "defaultPort": 8080},
        {"id": "host-python", "name": "Cell host Python", "protocol": "grpc", "baseUrl": "grpc://127.0.0.1:9101", "defaultPort": 9101},
        {"id": "host-ts", "name": "Cell host TypeScript", "protocol": "grpc", "baseUrl": "grpc://127.0.0.1:9102", "defaultPort": 9102},
        {"id": "host-rust", "name": "Cell host Rust", "protocol": "grpc", "baseUrl": "grpc://127.0.0.1:9103", "defaultPort": 9103},
    ]
    endpoints = []
    for c in cells:
        menu = dict(c.raw.get("menu") or {"category": "Cells", "label": c.name, "interactionType": "trigger"})
        menu.setdefault("viewRoute", f"/#/cells/{c.name}")
        endpoints.append({
            "id": c.name, "service": "gateway", "protocol": "rest",
            "title": c.raw.get("summary", c.name), "description": f"{c.urn} (owner={c.owner})",
            "readOnly": "pure" in (c.raw.get("effects") or []) or "read_data" in (c.raw.get("effects") or []),
            "roles": ["dev", "agent"], "tags": [c.ns, c.owner],
            "rest": {"method": "POST", "path": f"/api/cells/{c.name}", "contentType": "application/json"},
            "parameters": [{"name": k, "type": REG_T(v), "location": "body",
                            "required": not v.optional} for k, v in c.input.items()],
            "nlIntents": [{"lang": lang, "phrases": ph} for lang, ph in (c.raw.get("nl") or {}).items()],
            "menuBinding": menu,
        })
        endpoints.append({
            "id": f"{c.name}.grpc", "service": f"host-{c.owner}", "protocol": "grpc",
            "title": f"{c.name} (gRPC CellHost.Invoke)", "readOnly": True,
            "description": f"polycell.v1.CellHost/Invoke urn={c.urn}",
        })
        endpoints.append({
            "id": f"{c.name}.mcp", "service": "gateway", "protocol": "mcp",
            "title": f"MCP tool {c.snake}", "readOnly": True,
        })
    for p in processes:
        name = p["process_ref"].split("/process/")[1].split("/")[0]
        endpoints.append({
            "id": f"process.{name}", "service": "gateway", "protocol": "rest", "title": p["title"],
            "description": p["process_ref"], "readOnly": False, "roles": ["dev", "agent"],
            "rest": {"method": "POST", "path": f"/api/process/{name}", "contentType": "application/json"},
            "nlIntents": [{"lang": "pl", "phrases": [f"uruchom {name}", "złóż zamówienie"]},
                          {"lang": "en", "phrases": [f"run {name}", "place order"]}],
            "menuBinding": {"category": "Procesy", "label": p["title"], "interactionType": "modal_form",
                            "viewRoute": f"/#/process/{name}"},
        })
    reg = {"schema": "wellmanifest.api-registry/v1", "version": "0.1.0",
           "metadata": {"title": "Polycell example registry", "description": BANNER},
           "services": services, "endpoints": endpoints}
    write(GEN / "registry.json", jdump(reg))
    # Indeks runtime dla gateway: URN -> owner/kontrakt (+ procesy POA)
    write(GEN / "cells.index.json", jdump({
        "cells": {c.urn: {"name": c.name, "owner": c.owner, "contract": c.interface_hash,
                          "persist": (c.raw.get("persist") or {}).get("table"),
                          "nl": c.raw.get("nl") or {}, "menu": c.raw.get("menu") or {},
                          "summary": c.raw.get("summary", ""),
                          "examples": c.raw.get("examples") or [],
                          "input": {k: v.__dict__ for k, v in c.input.items()},
                          "output": {k: v.__dict__ for k, v in c.output.items()}} for c in cells},
        "processes": {p["process_ref"].split("/process/")[1].split("/")[0]: p for p in processes},
    }))


def gen_openapi_mcp(cells) -> None:
    paths = {}
    tools = []
    for c in cells:
        paths[f"/api/cells/{c.name}"] = {"post": {
            "operationId": c.snake, "summary": c.raw.get("summary", ""), "x-urn": c.urn,
            "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": f"jsonschema/{c.name}.input.json"}}}},
            "responses": {"200": {"description": "ok", "content": {"application/json": {"schema": {"$ref": f"jsonschema/{c.name}.output.json"}}}}},
        }}
        tools.append({"name": c.snake, "description": f"{c.raw.get('summary', '')} [{c.urn}]",
                      "inputSchema": json.loads((GEN / "jsonschema" / f"{c.name}.input.json").read_text())})
    write(GEN / "openapi.json", jdump({"openapi": "3.1.0", "info": {"title": "polycell", "version": "0.1.0"}, "paths": paths}))
    write(GEN / "mcp-tools.json", jdump({"tools": tools}))


def gen_tests(cells, processes) -> None:
    cases = []
    for c in cells:
        for ex in c.raw.get("examples") or []:
            cases.append({"urn": c.urn, "name": f"{c.name}:{ex['name']}", "owner": c.owner,
                          "input": ex["input"], "output": ex["output"]})
        golden = ROOT / "tests" / "golden" / f"{c.name}.jsonl"  # realne wywołania legacy (adopt.py golden)
        if golden.exists():
            for i, line in enumerate(l for l in golden.read_text(encoding="utf-8").splitlines() if l.strip()):
                g = json.loads(line)
                cases.append({"urn": c.urn, "name": f"{c.name}:golden{i}", "owner": c.owner,
                              "input": g["input"], "output": g["output"]})
    write(ROOT / "tests" / "generated" / "cases.json", jdump(cases))
    # Scenariusze w formacie TestQL (TestTOON) - uruchamiane przez `testql` lub twin/scenario_runner.py
    for c in cells:
        lines = [f"# SCENARIO: {c.name} contract", "# TYPE: api", "# GENERATED: true", "",
                 "CONFIG[1]{key, value}:", "  base_url, ${GATEWAY_URL:-http://localhost:8080}", ""]
        exs = c.raw.get("examples") or []
        lines.append(f"API[{len(exs) + 1}]{{method, endpoint, expected_status, body}}:")
        lines.append("  GET, /health, 200, -")
        for ex in exs:
            lines.append(f"  POST, /api/cells/{c.name}, 200, {json.dumps(ex['input'], ensure_ascii=False)}")
        lines.append("")
        first = exs[-1]["output"] if exs else {}  # ASSERT dotyczy ostatniej odpowiedzi
        scal = {k: v for k, v in first.items() if not isinstance(v, (list, dict))}
        lines.append(f"ASSERT[{len(scal)}]{{field, operator, expected}}:")
        lines += [f"  output.{k}, ==, {json.dumps(v, ensure_ascii=False)}" for k, v in scal.items()]
        write(ROOT / "tests" / "generated" / f"{c.name}.testql.toon.yaml", "\n".join(lines) + "\n")
    # Ściśle zgodny z TestQL (3 kolumny): uruchom `testql tests/generated/smoke.testql.toon.yaml --url ...`
    gets = ["/health", "/api/registry", "/api/cells", "/api/hosts", "/api/invocations"] + \
           [f"/api/process/{p['process_ref'].split('/process/')[1].split('/')[0]}/plan" for p in processes]
    write(ROOT / "tests" / "generated" / "smoke.testql.toon.yaml", "\n".join(
        ["# SCENARIO: polycell smoke", "# TYPE: api", "# GENERATED: true", "",
         "CONFIG[1]{key, value}:", "  base_url, http://localhost:8080", "",
         f"API[{len(gets)}]{{method, endpoint, expected_status}}:"] + [f"  GET, {g}, 200" for g in gets]) + "\n")
    for p in processes:
        name = p["process_ref"].split("/process/")[1].split("/")[0]
        write(ROOT / "tests" / "generated" / f"process.{name}.cases.json", jdump(p.get("examples") or []))


